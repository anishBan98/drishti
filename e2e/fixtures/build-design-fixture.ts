const sg = (
  type: ActionType,
  title: string,
  impactLabel: string,
  why: string,
  extra: Partial<Suggestion> & { evidence?: string[]; stepVars?: Record<string, string | number> } = {},
): Suggestion => {
  const { evidence, stepVars, ...rest } = extra;
  const s = suggest(
    { type, context: `design|${title}`, title, why, impactLabel, confidence: 'medium', stepVars: stepVars ?? {} },
    Number.MAX_SAFE_INTEGER,
  );
  return { ...s, evidence: (evidence ?? []).map((label) => ({ label })), ...rest };
};
const d = (value: number, unit: 'pct' | 'pts' | 'x', good: boolean | null, flat = false) => ({
  value,
  unit,
  direction: flat ? ('flat' as const) : value > 0 ? ('up' as const) : ('down' as const),
  good,
});
const k = (id: string, label: string, display: string, extra: Partial<Kpi> = {}): Kpi => ({
  id,
  label,
  value: 0,
  display,
  ...extra,
});

